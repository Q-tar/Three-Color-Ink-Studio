param(
    [string]$InputPath = "$PSScriptRoot\..\assets\source.jpg",
    [int]$BlackThreshold = 180
)
$ErrorActionPreference = 'Stop'
Add-Type -AssemblyName System.Drawing
$epdRoot = Split-Path $PSScriptRoot -Parent
$width = 104
$height = 212
$source = [System.Drawing.Image]::FromFile((Resolve-Path -LiteralPath $InputPath).Path)
$canvas = New-Object System.Drawing.Bitmap $width,$height
$preview = New-Object System.Drawing.Bitmap $width,$height
$graphics = [System.Drawing.Graphics]::FromImage($canvas)
try {
    $graphics.Clear([System.Drawing.Color]::White)
    $graphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::HighQualityBicubic
    $graphics.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::HighQuality
    $scale = [Math]::Min($width / $source.Width, $height / $source.Height)
    $fitWidth = [Math]::Max(1, [int][Math]::Round($source.Width * $scale))
    $fitHeight = [Math]::Max(1, [int][Math]::Round($source.Height * $scale))
    $left = [int][Math]::Floor(($width - $fitWidth) / 2)
    $top = [int][Math]::Floor(($height - $fitHeight) / 2)
    $graphics.DrawImage($source, $left, $top, $fitWidth, $fitHeight)
    $black = New-Object byte[] ($width * $height / 8)
    $red = New-Object byte[] ($width * $height / 8)
    $blackPixels = 0
    $redPixels = 0
    for ($y = 0; $y -lt $height; $y++) {
        for ($x = 0; $x -lt $width; $x++) {
            $c = $canvas.GetPixel($x, $y)
            $luma = 0.299 * $c.R + 0.587 * $c.G + 0.114 * $c.B
            $index = $y * ($width / 8) + [int][Math]::Floor($x / 8)
            $mask = 0x80 -shr ($x % 8)
            # Keep saturated pink/red accents; cream/orange background stays white.
            $isRed = $c.R -ge 190 -and ($c.R - $c.G) -ge 40 -and $c.G -lt 185 -and $c.B -ge ($c.G - 15)
            if ($isRed) {
                $red[$index] = $red[$index] -bor $mask
                $preview.SetPixel($x, $y, [System.Drawing.Color]::Red)
                $redPixels++
            } elseif ($luma -lt $BlackThreshold) {
                $black[$index] = $black[$index] -bor $mask
                $preview.SetPixel($x, $y, [System.Drawing.Color]::Black)
                $blackPixels++
            } else {
                $preview.SetPixel($x, $y, [System.Drawing.Color]::White)
            }
        }
    }
    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add('// Generated by tools/convert_image.ps1. Native row-major 104x212, MSB first.')
    $lines.Add('// Bit=1 selects that pigment; white=0 in both planes. No overlapping pigments.')
    $lines.Add('#pragma once')
    $lines.Add('#include <stdint.h>')
    $lines.Add('#define EPD_IMAGE_WIDTH 104')
    $lines.Add('#define EPD_IMAGE_HEIGHT 212')
    foreach ($plane in @(@{Name='black'; Bytes=$black}, @{Name='red'; Bytes=$red})) {
        $lines.Add("static const uint8_t epd_image_$($plane.Name)[2756] = {")
        for ($i = 0; $i -lt $plane.Bytes.Length; $i += 16) {
            $last = [Math]::Min($i + 15, $plane.Bytes.Length - 1)
            $values = $plane.Bytes[$i..$last] | ForEach-Object { '0x{0:X2}' -f $_ }
            $lines.Add('    ' + ($values -join ', ') + ',')
        }
        $lines.Add('};')
    }
    # Decode the packed bytes and compare every pixel with the exported preview.
    for ($y = 0; $y -lt $height; $y++) {
        for ($x = 0; $x -lt $width; $x++) {
            $index = $y * ($width / 8) + [int][Math]::Floor($x / 8)
            $mask = 0x80 -shr ($x % 8)
            if (($black[$index] -band $red[$index]) -ne 0) { throw 'Overlapping pigments' }
            $expected = if ($black[$index] -band $mask) { [System.Drawing.Color]::Black } elseif ($red[$index] -band $mask) { [System.Drawing.Color]::Red } else { [System.Drawing.Color]::White }
            if ($preview.GetPixel($x, $y).ToArgb() -ne $expected.ToArgb()) { throw "Pixel packing mismatch at $x,$y" }
        }
    }
    [System.IO.File]::WriteAllLines("$epdRoot\main\epd_image.h", $lines, [System.Text.Encoding]::ASCII)
    $preview.Save("$epdRoot\assets\epd_preview.png", [System.Drawing.Imaging.ImageFormat]::Png)
    $large = New-Object System.Drawing.Bitmap ($width * 4),($height * 4)
    $largeGraphics = [System.Drawing.Graphics]::FromImage($large)
    try {
        $largeGraphics.InterpolationMode = [System.Drawing.Drawing2D.InterpolationMode]::NearestNeighbor
        $largeGraphics.PixelOffsetMode = [System.Drawing.Drawing2D.PixelOffsetMode]::Half
        $largeGraphics.DrawImage($preview, 0, 0, $large.Width, $large.Height)
        $large.Save("$epdRoot\assets\epd_preview_4x.png", [System.Drawing.Imaging.ImageFormat]::Png)
    } finally { $largeGraphics.Dispose(); $large.Dispose() }
    Write-Host "Generated 104x212; fitted image ${fitWidth}x${fitHeight} at ($left,$top); black=$blackPixels red=$redPixels; 5512 bytes. Pixel packing verified."
} finally {
    $graphics.Dispose()
    $canvas.Dispose()
    $preview.Dispose()
    $source.Dispose()
}
